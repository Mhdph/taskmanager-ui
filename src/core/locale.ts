export const displayLabel = (value: string | null | undefined) => (value ? labels[value] || value : '');
const numberFormatter = new Intl.NumberFormat('fa-IR', { useGrouping: false });
export const faNumber = (value: number) => numberFormatter.format(value);

export function activityDetail(value: string) {
  if (labels[value]) return labels[value];
  return value
    .replace(/^from /, 'از ')
    .replace(/ to /, ' به ')
    .replace(/^to /, 'به ');
}
